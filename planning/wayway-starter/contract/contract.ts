// WayWay JSON contract — the shapes every part of the app agrees on.
// Frontend, AI module, logic and evaluation script all follow these types.
// Change this file only after telling the whole team.
//
// Coordination follows Papachristou et al. (private preference extraction,
// iterative rounds, per-member evaluation). WayWay extends it with
// code-enforced hard constraints, a fairest option, consent-based group
// splitting, and fairness credits across the whole trip.

// ======================================================================
// Settings agreed by the team
// ======================================================================
export const SETTINGS = {
  maxRounds: 3,                 // refinement rounds before the final group vote
  roundTimeoutMin: 30,          // next round starts after 30 min, even if someone is silent
  satisfiedLevel: "same",       // a member is "satisfied" at this level or better
  maxDefinitelyNoPerDay: 2,     // each member can vote "definitely_no" at most twice a day
  quorumRatio: 0.6,             // a final vote needs at least 60% of the group to be valid,
                                // rounded UP: Math.ceil(0.6 * members) -> 4 members = 3 votes
  voteExtensionMin: 30,         // no quorum at the deadline: voting is extended by 30 min
  creditCapPerDecision: 3,      // max credits earned in one decision
  creditWeightStep: 0.1,        // each credit adds +0.1 to the member's weight
  maxWeight: 1.5,               // weight cap (reached at 5 credits)
} as const;

// ======================================================================
// Satisfaction scale (same scale for AI estimates and human votes)
// ======================================================================
export type SatisfactionLevel =
  | "must_go"
  | "want_to_go"
  | "same"
  | "lean_not_go"
  | "definitely_no";

// Numeric values used ONLY by code to compute metrics (never shown to users)
export const LEVEL_VALUE: Record<SatisfactionLevel, number> = {
  must_go: 10,
  want_to_go: 7.5,
  same: 5,
  lean_not_go: 2.5,
  definitely_no: 0,
};

// ======================================================================
// Places (curated dataset)
// ======================================================================
export interface Spot {
  id: string;                   // short slug, e.g. "tnm"
  name: string;
  category: "museum" | "temple" | "food" | "shopping" | "nature" | "nightlife" | "hotel";
  price: number;                // estimated cost per person, JPY
  dietTags: string[];           // food spots only: ["vegetarian", "halal", ...]
  durationMin: number;
  openHours: string;            // "09:30-17:00"
  area: string;
  lat: number;
  lng: number;
}

// ======================================================================
// People and trip
// ======================================================================
export interface HardConstraints {   // confirmed by the user, enforced by code
  diet: string[];
  allergies: string[];
  maxBudget: number;                 // per person for the trip, JPY
}

export interface MemberProfile {
  id: string;                        // uuid (generated by Supabase)
  name: string;
  hard: HardConstraints;
  interests: string[];
  pace: "relaxed" | "moderate" | "packed";
  sleep: "early_bird" | "night_owl" | "flexible";
  privateNote: string;               // seen by WayWay only, never shown to the group
  preferenceStatements: string[];    // extracted from private chats (theta_i in Papachristou et al.)
  fairnessCredits: number;           // hidden from the UI, managed by code only
  definitelyNoUsedToday: number;     // resets every day, max SETTINGS.maxDefinitelyNoPerDay
}

export interface Trip {
  id: string;                        // uuid
  name: string;
  city: string;
  startDate: string;                 // "2026-11-21"
  endDate: string;
  timezone: string;                  // "Asia/Tokyo": used for deadlines and the daily "definitely_no" reset
  goal: "relaxed" | "balanced" | "packed";   // shared trip goal
  members: MemberProfile[];
}

// ======================================================================
// Group chat
// ======================================================================
export interface ChatMessage {
  id: string;                        // uuid
  tripId: string;
  senderId: string;                  // member id, or "wayway"
  text: string;
  createdAt: string;                 // ISO date
  optionSetId?: string;              // set when the message carries option cards
}

// ======================================================================
// Private chat with WayWay (one thread per member)
// ======================================================================
export interface PrivateMessage {
  id: string;                        // uuid
  tripId: string;
  memberId: string;                  // owner of the private thread
  sender: "member" | "wayway";
  text: string;
  createdAt: string;
  round?: number;                    // round the message reacts to
}

export interface PreferenceUpdate {  // output of extractPreferences (LLM)
  memberId: string;
  round: number;
  statements: string[];              // new or updated preference statements
  hardConstraintsToConfirm?: Partial<HardConstraints>;  // applied only after the user confirms
}

// ======================================================================
// Options proposed by WayWay
// ======================================================================
export interface MemberScore {
  memberId: string;
  level: SatisfactionLevel;
  source: "ai_estimate" | "vote";    // lets us measure how often the AI guessed right
  reason: string;                    // "Loves museums"
}

export interface Branch {
  memberIds: string[];               // members of this sub-group
  spots: string[];                   // spot ids
}

export interface OptionMetrics {     // computed by code (rankOptions), never by the LLM
  mean: number;                      // average of LEVEL_VALUE
  min: number;                       // least satisfied member
  gini: number;                      // 0 = equal, 1 = very unequal
  satisfactionRatio: number;         // share of members at "same" or better
  weightedTotal: number;             // total using fairness-credit weights
}

export interface Option {
  id: "A" | "B" | "C";
  kind: "best_total" | "fairest" | "split";
  title: string;
  spots: string[];                   // best_total / fairest
  branches?: Branch[];               // split only (max 2 branches)
  rendezvous?: { spotId: string; time: string };   // split only
  scores: MemberScore[];
  satisfiedMemberIds: string[];      // shown on the card: "Works for Mia, Ken, Sarah"
  explanation: string;               // the trade-off in plain words
  assumptions: string[];             // "Everyone takes the subway"
  fairnessNote?: string;             // "Tom's choice is favored: he compromised yesterday" (no numbers)
  metrics?: OptionMetrics;
}

export interface TimeSlot {          // what the decision is about
  day: number;                       // 1 = first day of the trip
  start: string;                     // "12:00"
  end: string;                       // "14:00"
  label: string;                     // "Lunch, day 2"
}

export interface OptionSet {
  id: string;                        // uuid
  tripId: string;
  slot: TimeSlot;                    // the winning option is placed here in the itinerary
  round: number;                     // 1 to SETTINGS.maxRounds
  options: Option[];
  candidateOptionId: "A" | "B" | "C";   // best so far, carried to the next round
  status: "collecting_feedback" | "voting" | "decided";
  roundDeadline: string;             // ISO date = round start + roundTimeoutMin
  // Final vote only: if fewer than quorumRatio of members voted at the deadline,
  // the deadline moves by voteExtensionMin and WayWay reminds the group.
  voteDeadline?: string;
  voterIds?: string[];               // members who have voted so far
  // Perfect tie on the final vote: one revote (voteAttempt = 2).
  // Tie again: the candidate option wins.
  voteAttempt?: 1 | 2;
  chosenOptionId?: "A" | "B" | "C";
}

// ======================================================================
// Votes, critiques and decisions
// ======================================================================
export interface Vote {
  optionSetId: string;
  optionId: "A" | "B" | "C";
  memberId: string;
  level: SatisfactionLevel;          // "definitely_no" refused once the daily limit is reached
  critique?: string;                 // optional comment used to revise the options
  // Required on a "split" option for every member placed in a branch.
  // The split is applied only if ALL affected members answer true;
  // otherwise the best non-split option is chosen instead.
  acceptsSplit?: boolean;
}

// Fairness credits are earned ONLY at the final decision (not during rounds).
// Members who did not vote are ignored: no vote, no credits.
export interface CreditEvent {       // audit trail for fairness credits (hidden from the UI)
  memberId: string;
  optionSetId: string;
  change: number;                    // +3 earned, or reset when their favorite wins
  reason: "compromise" | "favorite_chosen";
}

export interface Decision {
  optionSetId: string;
  chosenOptionId: "A" | "B" | "C";
  voterIds: string[];                // at least quorumRatio of the group; non-voters are not counted
  splitAcceptedBy?: string[];        // split options need every affected member's consent
  resolvedBy: "vote" | "tie_candidate" | "split_refused";   // how the final choice was made
  creditEvents: CreditEvent[];
  decidedAt: string;
}

// ======================================================================
// Itinerary
// ======================================================================
export interface ItineraryItem {
  day: number;
  start: string;                     // "10:30"
  end: string;
  spotId?: string;                   // shared stop
  branches?: Branch[];               // when the group splits
}

// ======================================================================
// API: POST /api/chat (group chat)
// ======================================================================
export interface ChatRequest {
  tripId: string;
  message?: ChatMessage;             // a new message (may mention @WayWay)
  votes?: Vote[];                    // or new votes / critiques
  nextRound?: boolean;               // refine options with the new private feedback
}

export interface ChatResponse {
  messages: ChatMessage[];
  optionSet?: OptionSet;
  decision?: Decision;
  itinerary?: ItineraryItem[];
  errors?: {
    code: "definitely_no_limit" | "vote_closed" | "unknown_option";
    memberId?: string;
    message: string;                 // shown to that member only
  }[];
}

// ======================================================================
// API: POST /api/private (one member <-> WayWay)
// ======================================================================
export interface PrivateChatRequest {
  tripId: string;
  memberId: string;
  message: PrivateMessage;
}

export interface PrivateChatResponse {
  messages: PrivateMessage[];        // WayWay's private reply
  preferenceUpdate?: PreferenceUpdate;
}
